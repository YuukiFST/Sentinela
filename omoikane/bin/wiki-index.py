"""Regenerate index.md from page frontmatter.

Deterministic: the agent edits frontmatter, never index.md.
Usage: python omoikane/bin/wiki-index.py
"""
from __future__ import annotations

from wikilib import CODE_KEY, OMOIKANE, PAGE_TYPES, PRUNE_KEY, Page, load_pages

HEADINGS = {
    "domain": "Domain",
    "decision": "Decisions",
    "gotcha": "Gotchas",
    "practice": "Practices",
    "concept": "Concepts",
    "entity": "Entities",
    "source": "Sources",
    "query": "Queries",
}


def render(pages: list[Page]) -> str:
    """index.md for `pages`: one section per type in PAGE_TYPES order, entries sorted by title.

    Example: render([gotcha "g", summary "s", updated 2026-09-15, prune stale]) returns
    "# Index\\n...\\n## Gotchas (1)\\n\\n- [[g]] — s `2026-09-15` `prune: stale`\\n".
    """
    out = ["# Index", "", "Generated by `python omoikane/bin/wiki-index.py`. Edit page frontmatter, not this file.", ""]
    for kind in PAGE_TYPES:
        group = sorted(
            (p for p in pages if p.meta.get("type") == kind),
            key=lambda p: str(p.meta.get("title", p.slug)),
        )
        if not group:
            continue
        out.append(f"## {HEADINGS[kind]} ({len(group)})")
        out.append("")
        for p in group:
            # Source pages show the source's own date: the agent ranks sources by it when claims disagree.
            stamp = f"dated {p.meta.get('dated', '')}" if kind == "source" else str(p.meta.get("updated", ""))
            code = p.meta.get(CODE_KEY) or []
            where = f" `{', '.join(map(str, code))}`" if isinstance(code, list) and code else ""
            # A page /prune marked is waiting for the human to delete it; it must not read as current.
            mark = f" `{PRUNE_KEY}: {p.meta[PRUNE_KEY]}`" if p.meta.get(PRUNE_KEY) else ""
            out.append(f"- [[{p.slug}]] — {p.meta.get('summary', '')}{where} `{stamp}`{mark}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    pages = load_pages()
    # Explicit LF: on Windows text mode would write CRLF and the CI freshness check would see a diff.
    (OMOIKANE / "index.md").write_text(render(pages), encoding="utf-8", newline="\n")
    print(f"index.md: {len(pages)} pages")


if __name__ == "__main__":
    main()
